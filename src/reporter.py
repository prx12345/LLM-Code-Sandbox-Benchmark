"""Result aggregation and rendering.

Turns an :class:`evaluator.EvaluationResult` into:

* a **structured JSON report** (stable ``schema_version``, machine-readable,
  suitable for dashboards / regression tracking / CI artifacts), and
* a **Markdown scorecard** (human-readable verdict, metric summary,
  per-case table and failure details).

The Markdown renderer works off the JSON dict, so both outputs are always
derived from a single source of truth.
"""

from __future__ import annotations

import json
import platform
import sys
from dataclasses import asdict
from datetime import datetime, timezone
from pathlib import Path
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:  # avoid an import cycle at runtime; used for typing only
    from evaluator import EvaluationResult

SCHEMA_VERSION: str = "1.0"
TOOL_NAME: str = "llm-code-benchmark"

_STATUS_LABELS: dict[str, str] = {
    "ok": "ok",
    "timeout": "timeout",
    "memory_exceeded": "memory exceeded",
    "runtime_error": "runtime error",
    "crashed": "crashed",
    "protocol_error": "protocol error",
}


def build_report(evaluation: "EvaluationResult", *, config: dict[str, Any]) -> dict[str, Any]:
    """Assemble the canonical JSON-serializable report dictionary.

    Args:
        evaluation: Aggregated evaluation produced by :class:`evaluator.Evaluator`.
        config: Run configuration (paths, limits, flags) echoed into the
            report for reproducibility.
    """
    return {
        "schema_version": SCHEMA_VERSION,
        "tool": TOOL_NAME,
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "environment": {
            "python": sys.version.split()[0],
            "platform": platform.platform(),
        },
        "config": config,
        "summary": {
            "suite": evaluation.suite_name,
            "function": evaluation.function_name,
            "candidate": evaluation.code_path,
            "verdict": evaluation.verdict,
            "score": evaluation.score,
            "accuracy_pct": evaluation.accuracy_pct,
            "cases_passed": evaluation.passed_count,
            "cases_total": evaluation.total_count,
            "category_stats": evaluation.category_stats,
            "timing_ms": evaluation.timing_ms,
            "memory": evaluation.memory,
            "complexity": (
                {
                    **asdict(evaluation.complexity),
                    "contested": evaluation.complexity.contested,
                }
                if evaluation.complexity
                else None
            ),
        },
        "cases": [asdict(case) for case in evaluation.cases],
    }


def write_json(report: dict[str, Any], path: str | Path) -> Path:
    """Write the JSON report to *path* (creating parent directories)."""
    output_path = Path(path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    return output_path


# --------------------------------------------------------------------------
# Markdown scorecard
# --------------------------------------------------------------------------


def render_scorecard(report: dict[str, Any]) -> str:
    """Render a Markdown scorecard from a report dictionary."""
    summary = report["summary"]
    verdict_icon = "✅" if summary["verdict"] == "PASS" else "❌"
    lines: list[str] = []

    lines.append("# 🧪 Evaluation Scorecard")
    lines.append("")
    lines.append(
        f"**Candidate:** `{summary['candidate']}` · **Function:** `{summary['function']}`"
    )
    lines.append(f"**Suite:** {summary['suite']}")
    lines.append("")
    lines.append(
        f"## Verdict: {verdict_icon} {summary['verdict']} — Score {summary['score']:.1f} / 100"
    )
    lines.append("")

    lines.extend(_summary_table(summary, report["config"]))
    lines.append("")
    lines.extend(_case_table(report["cases"]))

    failures = [case for case in report["cases"] if not case["passed"]]
    lines.append("")
    lines.append("## Failures")
    lines.append("")
    if not failures:
        lines.append("_None — all cases passed._ 🎉")
    else:
        lines.extend(_failure_details(failures))

    lines.append("")
    lines.append("---")
    lines.append(
        f"_Generated by {report['tool']} (schema {report['schema_version']}) "
        f"at {report['generated_at']} · Python {report['environment']['python']}_"
    )
    lines.append("")
    return "\n".join(lines)


def write_markdown(markdown: str, path: str | Path) -> Path:
    """Write the Markdown scorecard to *path* (creating parent directories)."""
    output_path = Path(path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(markdown, encoding="utf-8")
    return output_path


# --------------------------------------------------------------- internals


def _summary_table(summary: dict[str, Any], config: dict[str, Any]) -> list[str]:
    """Build the top-level metric table."""
    rows: list[tuple[str, str]] = [
        (
            "Accuracy",
            f"{summary['cases_passed']}/{summary['cases_total']} cases "
            f"({summary['accuracy_pct']:.1f}%)",
        )
    ]

    category_bits = [
        f"{name} {stats['passed']}/{stats['total']}"
        for name, stats in summary["category_stats"].items()
    ]
    if category_bits:
        rows.append(("By category", " · ".join(category_bits)))

    timing = summary.get("timing_ms")
    if timing:
        rows.append(
            (
                "Exec time (mean · median)",
                f"{timing['mean_ms']:.3f} ms · {timing['median_ms']:.3f} ms",
            )
        )
        rows.append(
            ("Exec time (p95 · max)", f"{timing['p95_ms']:.3f} ms · {timing['max_ms']:.3f} ms")
        )

    memory = summary.get("memory")
    if memory and memory.get("peak_rss_mb") is not None:
        rows.append(("Peak process RSS", f"{memory['peak_rss_mb']:.1f} MB"))
    if memory and memory.get("peak_tracemalloc_kb") is not None:
        rows.append(
            ("Peak Python allocations", f"{memory['peak_tracemalloc_kb']:.1f} KB")
        )

    complexity = summary.get("complexity")
    if complexity:
        reliability = "" if complexity["reliable"] else " · low confidence"
        contested = (
            f" · close second: {complexity['runner_up_label']}"
            if complexity.get("contested")
            else ""
        )
        rows.append(
            (
                "Estimated complexity",
                f"{complexity['label']} (empirical, {complexity['sample_count']} samples"
                f"{contested}{reliability})",
            )
        )

    limits = config.get("limits") or {}
    if limits:
        memory_limit = limits.get("memory_mb")
        rows.append(
            (
                "Limits per case",
                f"{limits.get('wall_time_s', '?')} s wall · "
                f"{memory_limit if memory_limit else 'unlimited'} MB RAM",
            )
        )

    table = ["| Metric | Value |", "| --- | --- |"]
    table.extend(f"| {name} | {value} |" for name, value in rows)
    return table


def _case_table(cases: list[dict[str, Any]]) -> list[str]:
    """Build the per-case results table."""
    lines = [
        "## Per-case results",
        "",
        "| # | Case | Category | Result | Status | Time (ms) | RSS (MB) |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for index, case in enumerate(cases, start=1):
        result_icon = "✅" if case["passed"] else "❌"
        status = _STATUS_LABELS.get(case["status"], case["status"])
        if not case["passed"] and case["failure_reason"] == "wrong_answer":
            status = "wrong answer"
        time_ms = case["call_time_ms"]
        rss = case["max_rss_mb"]
        lines.append(
            f"| {index} | `{case['id']}` | {case['category']} | {result_icon} "
            f"| {status} "
            f"| {f'{time_ms:.3f}' if time_ms is not None else '—'} "
            f"| {f'{rss:.1f}' if rss is not None else '—'} |"
        )
    return lines


def _failure_details(failures: list[dict[str, Any]]) -> list[str]:
    """Render an explanatory block for every failed case."""
    lines: list[str] = []
    for case in failures:
        lines.append(f"### `{case['id']}` — {case['failure_reason']}")
        if case["description"]:
            lines.append(f"_{case['description']}_")
        lines.append("")
        lines.append("```")
        lines.append(f"expected: {json.dumps(case['expected'], ensure_ascii=False)}")
        lines.append(f"actual:   {json.dumps(case['actual'], ensure_ascii=False)}")
        lines.append("```")
        error = case.get("error")
        if error:
            message = error.get("message", "")
            lines.append(f"- **{error.get('type', 'Error')}**: {message}")
            trace = error.get("traceback")
            if trace:
                lines.append("")
                lines.append("<details><summary>Traceback</summary>")
                lines.append("")
                lines.append("```text")
                lines.append(trace.strip())
                lines.append("```")
                lines.append("")
                lines.append("</details>")
        if case["stderr"]:
            lines.append("")
            lines.append("```text")
            lines.append(case["stderr"].strip()[:1_500])
            lines.append("```")
        lines.append("")
    return lines
